import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.goto('/');await page.waitForFunction(()=>(window as any).reportstudioReady);});
test('subsection menu opens beside its trigger and selects the newly created section',async({page})=>{
 const dock=page.locator('.sections-bar');const cards=dock.locator('.section-card');const before=await cards.count();
 const parent=cards.first();const trigger=parent.getByLabel('Section options',{exact:true});await trigger.click();
 const popup=parent.locator('.section-popover');await expect(popup).toBeVisible();
 await expect.poll(async()=>{const a=(await trigger.boundingBox())!,b=(await popup.boundingBox())!;return Math.abs(b.y+b.height-a.y);}).toBeLessThanOrEqual(8);
 const a=(await trigger.boundingBox())!,b=(await popup.boundingBox())!;
 expect(Math.abs(b.y+b.height-a.y)).toBeLessThanOrEqual(8);
 expect(b.x).toBeLessThan(a.x+a.width);expect(b.x+b.width).toBeGreaterThan(a.x);
 await popup.getByRole('button',{name:'Add subsection',exact:true}).click();
 await expect(cards).toHaveCount(before+1);
 await expect(dock.locator('.section-card.selected')).toContainText('Section');
 const id=(await dock.locator('.section-card.selected').getAttribute('id'))!.replace('section-tab-','');
 await expect(page.locator('#report-section-'+id)).toBeInViewport();
 await page.getByRole('button',{name:'Undo',exact:true}).first().click();await expect(cards).toHaveCount(before);
});
test('Add section creates and selects a detail group, including on a blank document',async({page})=>{
 const dock=page.locator('.sections-bar');const before=await dock.locator('.section-card').count();
 await dock.getByLabel('Add section',{exact:true}).click();
 const menu=dock.locator('.add-section-menu');await expect(menu.locator('.section-popover')).toBeVisible();
 await menu.locator('.section-popover button').first().click();
 await expect(dock.locator('.section-card')).toHaveCount(before+3);
 await expect(dock.locator('.section-card.selected')).toContainText('Details');
 await expect(menu).not.toHaveAttribute('open','');
 await page.getByRole('button',{name:'New',exact:true}).click();
 await expect(dock.locator('.section-card')).toHaveCount(7);
 await dock.getByLabel('Add section',{exact:true}).click();
 await menu.getByRole('button',{name:'Details',exact:true}).click();
 await expect(dock.locator('.section-card')).toHaveCount(10);
 await expect(dock.locator('.section-card.selected')).toContainText('Details');
});

test('section menus close when clicking outside, opening another menu, or pressing Escape',async({page})=>{
 const dock=page.locator('.sections-bar');
 const sections=dock.locator('.section-card');
 const first=sections.nth(0).locator('.section-menu');
 const second=sections.nth(1).locator('.section-menu');
 const add=dock.locator('.add-section-menu');
 await first.locator('summary').click();
 await expect(first.locator('.section-popover')).toBeVisible();
 await page.locator('.status-bar').click();
 await expect(first.locator('.section-popover')).toBeHidden();
 await first.locator('summary').click();
 await second.locator('summary').click();
 await expect(first.locator('.section-popover')).toBeHidden();
 await expect(second.locator('.section-popover')).toBeVisible();
 await add.locator('summary').click();
 await expect(second.locator('.section-popover')).toBeHidden();
 await expect(add.locator('.section-popover')).toBeVisible();
 await add.locator('summary').press('Escape');
 await expect(add.locator('.section-popover')).toBeHidden();
 await first.locator('summary').click();
 await first.getByRole('checkbox',{name:'Section visible',exact:true}).uncheck();
 await expect(first.locator('.section-popover')).toBeHidden();
 await first.locator('summary').click();
 await expect(first.getByRole('checkbox',{name:'Section visible',exact:true})).not.toBeChecked();
 await first.getByRole('checkbox',{name:'Section visible',exact:true}).check();
});
